from fastapi import APIRouter, Depends
from fastapi.responses import PlainTextResponse
from database import get_db
from utils.auth import get_current_user, UserSession
from datetime import datetime, timedelta

router = APIRouter(prefix="/api/export", tags=["export"])

@router.get("/therapist", response_class=PlainTextResponse)
async def export_therapist_report(
    current_user: UserSession = Depends(get_current_user),
    db = Depends(get_db)
):
    # Fetch last 30 days of journals and moods
    thirty_days_ago = datetime.utcnow() - timedelta(days=30)
    
    moods_cursor = db.moods.find({
        "user_id": current_user.id,
        "created_at": {"$gte": thirty_days_ago}
    }).sort("created_at", -1)
    moods = await moods_cursor.to_list(length=100)
    
    journals_cursor = db.journals.find({
        "user_id": current_user.id,
        "created_at": {"$gte": thirty_days_ago}
    }).sort("created_at", -1)
    journals = await journals_cursor.to_list(length=100)
    
    report = f"# Therapist Companion Report\n"
    report += f"**User:** {current_user.username}\n"
    report += f"**Date Range:** {thirty_days_ago.strftime('%Y-%m-%d')} to {datetime.utcnow().strftime('%Y-%m-%d')}\n\n"
    
    report += "## Summary of Last 30 Days\n"
    report += f"- Total Mood Logs: {len(moods)}\n"
    report += f"- Total Journals: {len(journals)}\n\n"
    
    report += "## Mood Trends\n"
    for mood in moods:
        report += f"- {mood['created_at'].strftime('%Y-%m-%d %H:%M')}: Score {mood.get('score', '?')}/10, Label: {mood.get('label', 'Unknown')}\n"
        if mood.get('notes'):
            report += f"  - Notes: {mood['notes']}\n"
            
    report += "\n## Journal AI Insights\n"
    for journal in journals:
        report += f"### {journal['created_at'].strftime('%Y-%m-%d %H:%M')} - {journal.get('title', 'Entry')}\n"
        if journal.get("ai_summary"):
            report += f"**Summary:** {journal['ai_summary']}\n"
        if journal.get("ai_emotions"):
            emotions = ", ".join([f"{e['name']} ({e['intensity']})" for e in journal['ai_emotions']])
            report += f"**Emotions Detected:** {emotions}\n"
        if journal.get("ai_wellbeing_score"):
            report += f"**Wellbeing Score:** {journal['ai_wellbeing_score']}/10\n"
        if journal.get("ai_corrective_actions"):
            actions = ", ".join(journal["ai_corrective_actions"])
            report += f"**Action Plan:** {actions}\n"
        report += "\n"
        
    report += "---\n*Generated by ShadowMind v4*"
    
    return report
